/** process.env without the developer's global Bun config: HOME and XDG_CONFIG_HOME move into the temp base, BUN_CONFIG_* is dropped. */
function isolatedBunEnv(base: string): NodeJS.ProcessEnv {
  const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('BUN_CONFIG_')));
  for (const dir of ['home', 'xdg']) fs.mkdirSync(path.join(base, dir), { recursive: true });
  return { ...env, HOME: path.join(base, 'home'), XDG_CONFIG_HOME: path.join(base, 'xdg') };
}

function tempBase(): string {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'gstack-prod-deps-'));
  bases.push(base);
  return base;
}

/** A bash function sliced out of a script, by its `name() {` line through the closing `}`. */
function sliceFunction(source: string, name: string): string {
  const start = source.indexOf(`\n${name}() {\n`);
  if (start === -1) throw new Error(`${name}() not found`);
  const end = source.indexOf('\n}\n', start);
  return source.slice(start + 1, end + 3);
}

/**
 * A bun that records each argv line. Like Bun, a --frozen-lockfile install fails
 * ($FROZEN_RC) until `install --lockfile-only` has refreshed the lockfile; any other
 * call exits $FALLBACK_RC.
 */
function stubBun(base: string): { bun: string; calls: () => string[] } {
  const log = path.join(base, 'calls');
  const bun = path.join(base, 'bun');
  const fresh = path.join(base, 'lockfile-refreshed');
  fs.writeFileSync(bun, `#!/usr/bin/env bash\necho "$*" >> ${JSON.stringify(log)}\ncase "$*" in\n  *--frozen-lockfile*) [ -f ${JSON.stringify(fresh)} ] && exit 0; exit "\${FROZEN_RC:-0}" ;;\n  *--lockfile-only*) rc="\${FALLBACK_RC:-0}"; [ "$rc" -eq 0 ] && : > ${JSON.stringify(fresh)}; exit "$rc" ;;\nesac\nexit "\${FALLBACK_RC:-0}"\n`, { mode: 0o755 });
  return { bun, calls: () => (fs.existsSync(log) ? fs.readFileSync(log, 'utf-8').trim().split('\n') : []) };
}

